#!/usr/bin/env node
/*
 * Precompute the data for exchange.html ("What is a cycle worth?").
 *   node tools/precompute-exchange.js   -> writes data/exchange-presets.js
 *
 * 1. Each network with no exploration: how often it reaches the right consensus.
 * 2. The complete network with exploration: doubters test B with probability
 *    x = budget / horizon per round, for several budgets and horizons.
 * Uses the same engine as the browser (models/zollman.js).
 */
const fs = require('fs');
const path = require('path');
const rng = require('../lib/rng.js');
const NETS = require('../lib/networks.js');
const Z = require('../models/zollman.js');

const SETTINGS = { N: 10, eps: 0.001, n: 1000 };
const TOPO_RUNS = +process.env.TOPO_RUNS || 20000;
const CURVE_RUNS = +process.env.CURVE_RUNS || 20000;
const SIDE_RUNS = +process.env.SIDE_RUNS || 6000;

const TOPOLOGIES = [
  { id: 'complete', type: 'complete', params: {} },
  { id: 'wheel', type: 'wheel', params: {} },
  { id: 'ring3', type: 'ringLattice', params: { k: 3 } },
  { id: 'ring2', type: 'ringLattice', params: { k: 2 } },
  { id: 'clusters2', type: 'clusters', params: { c: 2 } },
  { id: 'clusters3', type: 'clusters', params: { c: 3 } },
  { id: 'smallWorld', type: 'smallWorld', params: { k: 2, beta: 0.1 } },
  { id: 'erdos', type: 'erdosRenyi', params: { p: 0.3 } },
  { id: 'scaleFree2', type: 'scaleFree', params: { m: 2 } },
  { id: 'scaleFree1', type: 'scaleFree', params: { m: 1 } },
  { id: 'grid', type: 'grid', params: {} },
  { id: 'star', type: 'star', params: {} },
  { id: 'cycle', type: 'cycle', params: {} },
  { id: 'line', type: 'line', params: {} },
];
const BUDGETS = [0.1, 0.3, 1, 3, 10, 30, 100, 300];
const HORIZONS = [2000, 10000, 50000];
const MAIN_H = 10000;

function tally(runs, make, explore, cap, seedTag) {
  const rand = rng.mulberry32(rng.mix(20261105, seedTag));
  const a = { runs: 0, correct: 0, incorrect: 0, timeout: 0, roundsCorrect: 0, explorations: 0, everTrapped: 0 };
  const statsAcc = { edges: 0, meanDegree: 0, components: 0 };
  let fixed = null;
  for (let r = 0; r < runs; r++) {
    const g = make(rand, r) || fixed;
    if (!fixed && !make.random) fixed = g;
    const res = Z.simulate(g, SETTINGS.eps, SETTINGS.n, Z.randomPriors(SETTINGS.N, rand), rand, cap, 0.99, explore);
    a.runs++;
    a[res.outcome]++;
    if (res.outcome === 'correct') a.roundsCorrect += res.rounds;
    a.explorations += res.explorations;
    if (res.everTrapped) a.everTrapped++;
    if (r < 200) {
      const s = NETS.stats(g);
      statsAcc.edges += s.edges; statsAcc.meanDegree += s.meanDegree; statsAcc.components += s.components;
    }
  }
  const k = Math.min(200, runs);
  a.stats = { edges: statsAcc.edges / k, meanDegree: statsAcc.meanDegree / k, components: statsAcc.components / k };
  return a;
}

const t0 = Date.now();
const topologies = TOPOLOGIES.map((d, idx) => {
  const random = !!NETS.TYPES[d.type].random;
  let cached = null;
  const make = (rand) => {
    if (random) return NETS.make(d.type, SETTINGS.N, d.params, (rand() * 4294967296) >>> 0);
    return cached || (cached = NETS.make(d.type, SETTINGS.N, d.params, 0));
  };
  make.random = random;
  const a = tally(TOPO_RUNS, make, 0, 20000, 100 + idx);
  console.error(`${d.id}: P ${(a.correct / a.runs).toFixed(4)}  (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
  return Object.assign({}, d, { label: NETS.describe(d.type, d.params), acc: a });
});

const complete = NETS.make('complete', SETTINGS.N);
const makeComplete = () => complete;
const curves = HORIZONS.map((H, hi) => ({
  horizon: H,
  points: BUDGETS.map((B, bi) => {
    const runs = H === MAIN_H ? CURVE_RUNS : SIDE_RUNS;
    const a = tally(runs, makeComplete, B / H, H, 1000 + hi * 100 + bi);
    console.error(`H ${H} budget ${B}: P ${(a.correct / a.runs).toFixed(4)}  (${((Date.now() - t0) / 1000).toFixed(0)} s)`);
    return Object.assign({ budget: B, rate: B / H }, a);
  }),
}));

const out = { settings: SETTINGS, mainHorizon: MAIN_H, topologies, curves, generated: new Date().toISOString().slice(0, 10) };
const file = path.join(__dirname, '..', 'data', 'exchange-presets.js');
fs.writeFileSync(
  file,
  '/* Generated by tools/precompute-exchange.js. Do not edit by hand. */\n' +
    '(function (root) {\n  root.NET = root.NET || {};\n  root.NET.exchangePresets = ' +
    JSON.stringify(out) +
    ';\n})(typeof self !== "undefined" ? self : this);\n'
);
console.error(`wrote ${file} in ${((Date.now() - t0) / 1000).toFixed(0)} s`);

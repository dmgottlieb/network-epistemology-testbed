#!/usr/bin/env node
/*
 * Precompute the Monte Carlo presets shown on zollman.html, so the page opens
 * with results. Uses exactly the same simulation code as the browser.
 *   node tools/precompute-presets.js            -> writes data/zollman-presets.js
 */
const fs = require('fs');
const path = require('path');
const rng = require('../lib/rng.js');
const NETS = require('../lib/networks.js');
const Z = require('../models/zollman.js');

const NET_DEFS = {
  complete: { type: 'complete', params: {} },
  cycle: { type: 'cycle', params: {} },
  wheel: { type: 'wheel', params: {} },
};

const PRESETS = {
  zollman: { vary: 'N', xs: [3, 4, 5, 6, 7, 8, 9, 10], fixed: { N: 10, eps: 0.001, n: 1000 }, runs: 5000, cap: 10000, nets: ['complete', 'cycle', 'wheel'] },
  eps: { vary: 'eps', xs: [0.001, 0.002, 0.005, 0.01, 0.015, 0.02, 0.025, 0.05], fixed: { N: 10, eps: 0.001, n: 1000 }, runs: 5000, cap: 10000, nets: ['complete', 'cycle'] },
  trials: { vary: 'n', xs: [10, 20, 50, 100, 200, 500, 1000, 2000, 5000, 10000], fixed: { N: 10, eps: 0.01, n: 1000 }, runs: 3000, cap: 10000, nets: ['complete', 'cycle'] },
  size: { vary: 'N', xs: [10, 20, 30, 50, 75, 100], fixed: { N: 10, eps: 0.001, n: 1000 }, runs: 1000, cap: 10000, nets: ['complete', 'cycle'] },
};

const only = process.argv[2];
const out = {};
for (const [key, cfg] of Object.entries(PRESETS)) {
  if (only && only !== key) continue;
  const t0 = Date.now();
  const acc = {};
  for (const id of cfg.nets) acc[id] = [];
  cfg.xs.forEach((x, xi) => {
    for (const id of cfg.nets) {
      const N = cfg.vary === 'N' ? x : cfg.fixed.N;
      const eps = cfg.vary === 'eps' ? x : cfg.fixed.eps;
      const n = cfg.vary === 'n' ? x : cfg.fixed.n;
      const def = NET_DEFS[id];
      const g = NETS.make(def.type, N, def.params, 0);
      const rand = rng.mulberry32(rng.mix(20261104, xi, id.length, id.charCodeAt(0)));
      const a = { runs: 0, correct: 0, incorrect: 0, timeout: 0, roundsCorrect: 0 };
      for (let r = 0; r < cfg.runs; r++) {
        const res = Z.simulate(g, eps, n, Z.randomPriors(N, rand), rand, cfg.cap);
        a.runs++;
        a[res.outcome]++;
        if (res.outcome === 'correct') a.roundsCorrect += res.rounds;
      }
      acc[id].push(a);
    }
  });
  out[key] = Object.assign({}, cfg, { acc });
  console.error(`${key}: ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}

const file = path.join(__dirname, '..', 'data', 'zollman-presets.js');
const body =
  '/* Generated by tools/precompute-presets.js. Do not edit by hand. */\n' +
  '(function (root) {\n  root.NET = root.NET || {};\n  root.NET.zollmanPresets = ' +
  JSON.stringify(out) +
  ';\n})(typeof self !== "undefined" ? self : this);\n';
if (!only) fs.writeFileSync(file, body);
else console.log(JSON.stringify(out[only].acc));

#!/usr/bin/env node
/*
 * Precompute Kummerfeld & Zollman (2016) Figure 6-style curves for exchange.html.
 *   node tools/precompute-kz.js   -> writes data/kz-presets.js
 */
const fs = require('fs');
const path = require('path');
const rng = require('../lib/rng.js');
const NETS = require('../lib/networks.js');
const KZ = require('../models/kummerfeld-zollman.js');

const RUNS = +process.env.RUNS || 60000;
const EPS = [];
for (let e = 0; e <= 0.5001; e += 0.02) EPS.push(+e.toFixed(2));
const SIZES = [4, 6, 8];
const out = { runs: RUNS, eps: EPS, rounds: 50, mean: 1, sd: 9, sizes: {} };
const t0 = Date.now();
for (const N of SIZES) {
  out.sizes[N] = {};
  for (const type of ['complete', 'cycle']) {
    const g = NETS.make(type, N);
    out.sizes[N][type] = EPS.map((eps, i) => {
      const r = KZ.performance(g, eps, RUNS, rng.mulberry32(rng.mix(N, i, type.length, 2016)));
      return [+r.mean.toFixed(5), +r.se.toFixed(5)];
    });
    console.error(`N ${N} ${type}: ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
}
fs.writeFileSync(
  path.join(__dirname, '..', 'data', 'kz-presets.js'),
  '/* Generated by tools/precompute-kz.js. Do not edit by hand. */\n(function (root) {\n  root.NET = root.NET || {};\n  root.NET.kzPresets = ' +
    JSON.stringify(out) + ';\n})(typeof self !== "undefined" ? self : this);\n'
);
console.error('done');

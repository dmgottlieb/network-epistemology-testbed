#!/usr/bin/env node
/*
 * Kummerfeld & Zollman (2016) Choose-Your-epsilon game, for freerider.html.
 *   node tools/precompute-freerider.js   -> writes data/freerider-presets.js
 * For each group size and network: the hero's payoff for each (group eps,
 * hero eps) pair, the hero's best response, and the community's payoff when
 * everyone plays the same eps.
 */
const fs = require('fs');
const path = require('path');
const rng = require('../lib/rng.js');
const NETS = require('../lib/networks.js');
const KZ = require('../models/kummerfeld-zollman.js');

const RUNS = +process.env.RUNS || 10000;
const PERF_RUNS = +process.env.PERF_RUNS || 40000;
const grid = (hi, step) => { const o = []; for (let e = 0; e <= hi + 1e-9; e += step) o.push(+e.toFixed(2)); return o; };
const EG = grid(0.3, 0.02), EH = grid(0.4, 0.02), EC = grid(0.5, 0.02);
const out = { runs: RUNS, perfRuns: PERF_RUNS, eg: EG, eh: EH, ec: EC, rounds: 50, mean: 1, sd: 9, sizes: {} };
const t0 = Date.now();
for (const N of [2, 4, 6, 8]) {
  out.sizes[N] = {};
  for (const type of N === 2 ? ['complete'] : ['complete', 'cycle']) {
    const g = NETS.make(type, N);
    const hero = EG.map((eg, gi) => Array.from(KZ.heroPayoffs(g, eg, EH, RUNS, rng.mulberry32(rng.mix(N, gi, type.length, 11))), (v) => +v.toFixed(5)));
    const br = hero.map((ys) => +KZ.bestResponse(EH, ys).toFixed(4));
    const perf = EC.map((e, i) => +KZ.performance(g, e, PERF_RUNS, rng.mulberry32(rng.mix(N, i, type.length, 12))).mean.toFixed(5));
    out.sizes[N][type] = { hero, br, perf };
    console.error(`N ${N} ${type}: ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
}
fs.writeFileSync(path.join(__dirname, '..', 'data', 'freerider-presets.js'),
  '/* Generated by tools/precompute-freerider.js. Do not edit by hand. */\n(function (root) {\n  root.NET = root.NET || {};\n  root.NET.freeriderPresets = ' +
  JSON.stringify(out) + ';\n})(typeof self !== "undefined" ? self : this);\n');
console.error('done');

#!/usr/bin/env node
/*
 * Precompute the experiment presets shown on polarization.html.
 *   node tools/precompute-polarization.js   -> writes data/polarization-presets.js
 */
const fs = require('fs');
const path = require('path');
const SW = require('../models/polarization-sweep.js');

const BASE = { N: 10, eps: 0.2, n: 50, m: 2, network: 'complete', order: 'sequential', rule: 'ignore' };
const M_VALUES = [1, 1.1, 1.2, 1.3, 1.4, 1.5, 1.75, 2, 2.5, 3];

const PRESETS = {
  fig2: {
    title: 'Mistrust breeds polarization (O’Connor & Weatherall Fig. 2)',
    metric: 'polarized',
    vary: 'm', xs: M_VALUES, seriesBy: 'N', series: [6, 10, 20],
    fixed: Object.assign({}, BASE), runs: 2000, cap: 20000,
  },
  fig3: {
    title: 'Clearer evidence resists it (Fig. 3)',
    metric: 'polarized',
    vary: 'eps', xs: [0.01, 0.02, 0.05, 0.1, 0.15, 0.2, 0.25], seriesBy: 'm', series: [1.1, 1.3, 1.5, 2],
    fixed: Object.assign({}, BASE, { n: 20 }), runs: 1000, cap: 20000,
  },
  fig4: {
    title: 'Even mild mistrust slows consensus (Fig. 4)',
    metric: 'rounds',
    vary: 'n', xs: [1, 2, 5, 10, 20, 50, 100], seriesBy: 'm', series: [0, 1],
    fixed: Object.assign({}, BASE, { N: 6, eps: 0.05 }), runs: 1000, cap: 20000,
  },
  order: {
    title: 'An unstated detail: update order',
    metric: 'polarized',
    vary: 'm', xs: M_VALUES, seriesBy: 'order', series: ['sequential', 'simultaneous'],
    fixed: Object.assign({}, BASE), runs: 2000, cap: 20000,
  },
  rule: {
    title: 'Ignoring vs. anti-updating',
    metric: 'leftBehind',
    vary: 'm', xs: M_VALUES, seriesBy: 'rule', series: ['ignore', 'anti'],
    fixed: Object.assign({}, BASE), runs: 2000, cap: 20000,
  },
  networks: {
    title: 'Beyond the paper: sparse networks',
    metric: 'polarized',
    vary: 'm', xs: M_VALUES, seriesBy: 'network', series: ['complete', 'wheel', 'cycle'],
    fixed: Object.assign({}, BASE), runs: 1000, cap: 20000,
  },
};

const out = {};
const t0 = Date.now();
for (const [key, cfg] of Object.entries(PRESETS)) {
  const sweep = SW.createSweep(cfg, 20261105 + key.length);
  while (!sweep.next(1e9));
  out[key] = Object.assign({}, cfg, { acc: sweep.acc });
  console.error(`${key}: ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}
const file = path.join(__dirname, '..', 'data', 'polarization-presets.js');
fs.writeFileSync(
  file,
  '/* Generated by tools/precompute-polarization.js. Do not edit by hand. */\n' +
    '(function (root) {\n  root.NET = root.NET || {};\n  root.NET.polarizationPresets = ' +
    JSON.stringify(out) +
    ';\n})(typeof self !== "undefined" ? self : this);\n'
);
console.error('wrote ' + file);
